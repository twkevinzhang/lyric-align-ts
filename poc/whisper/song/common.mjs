import { readFile, mkdir, realpath } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import {threadConfig} from './thread-config.mjs';
import {parseSrt} from '../../../spike/app/lib/reference.ts';
import {inferenceConfig} from './inference-config.mjs';
import {spokenLyrics} from './lyrics.mjs';
import {cachePosition} from './cache-position.mjs';
export const cachePolicy=process.env.SONG_CACHE_POSITION??'upstream';
cachePosition(0,cachePolicy);
export const inference=inferenceConfig();
export const audioTimeScale=Number(process.env.SONG_TIME_SCALE??'1');
if(![1,2,3,4].includes(audioTimeScale))throw Error('Invalid audio time scale');
export const language=process.env.SONG_LANGUAGE || 'en';
export const root = resolve(import.meta.dirname, '../../..');
export const local = resolve(root, '.local/whisper-poc');
export const threadSettings=threadConfig(process.env.SONG_THREADS ?? '1',process.env.SONG_POOL_SIZE ?? '6');
export const decoderThreads=threadConfig(process.env.SONG_DECODER_THREADS??String(threadSettings.threads),String(threadSettings.poolSize)).threads;
export const profile=process.env.SONG_OUTPUT || 'song';
if(!/^[a-z][a-z0-9-]*$/.test(profile)) throw new Error('Invalid SONG_OUTPUT');
export const out = resolve(local, profile);
export const media = process.env.SONG_DIR || 'C:/Users/DragonXwin10/Downloads/audio/TestSet/amazing_grace';
export const echo = await realpath(process.env.ECHOGARDEN_DIR || 'C:/Projects/lyric-align-ts/.local/echogarden-test/node_modules/echogarden');
export const official = path => import(pathToFileURL(resolve(echo, 'dist', path)).href);
export const hash = bytes => createHash('sha256').update(bytes).digest('hex');
export const lock = JSON.parse(await readFile(resolve(root, 'poc/whisper/lock.json')));
export const options = { model: inference.model, enableGPU: false, threadCount: threadSettings.threads, gpuDeviceIndex: 0, timestampAccuracy: 'medium', maxTokensPerPart: 448, endTokenThreshold: inference.endTokenThreshold };
export async function prepare() {
  await mkdir(out, {recursive:true});
  const pkg = JSON.parse(await readFile(resolve(echo,'package.json')));
  if(pkg.version !== '3.4.0') throw new Error('This benchmark pins Echogarden 3.4.0');
  const modelPath=resolve(local,inference.file);
  if(hash(await readFile(modelPath))!==inference.sha256) throw new Error('Model mismatch');
  const audioPath=resolve(media,process.env.SONG_AUDIO || '256k-16kHz-單聲道.wav');
  const lyricsPath=resolve(media,process.env.SONG_LYRICS || 'Original.txt');
  const lyricsBytes=await readFile(lyricsPath);
  const originalLyrics=lyricsPath.endsWith('.srt') ? parseSrt(lyricsBytes.toString('utf8')).map(c=>c.text).join('\n') : lyricsBytes.toString('utf8').replace(/^\uFEFF/,'');
  const annotationPolicy=process.env.SONG_ANNOTATIONS??'preserve';
  if(!['preserve','strip-translations'].includes(annotationPolicy))throw Error('Unknown annotation policy');
  const lyrics=annotationPolicy==='strip-translations'?spokenLyrics(originalLyrics):originalLyrics;
  const {ensureRawAudio}=await official('audio/AudioUtilities.js');
  const t=performance.now();
  const audio=await ensureRawAudio(audioPath,16000,1,{logLevel:'warning'});
  const audioPreparationSeconds=(performance.now()-t)/1000;
  const metadata={echogarden:pkg.version, sourceSha256:hash(await readFile(resolve(echo,'dist/recognition/WhisperSTT.js'))), modelSha256:inference.sha256,audioSha256:hash(await readFile(audioPath)),lyricsSha256:hash(lyricsBytes),pcmSha256:hash(Buffer.from(audio.audioChannels[0].buffer,audio.audioChannels[0].byteOffset,audio.audioChannels[0].byteLength)),audioSeconds:audio.audioChannels[0].length/16000,audioPreparationSeconds,options,referenceUsedForInference:false,mode:'guided-lyrics-alignment',crop:false,isolate:false};
  const driverHashes=Object.fromEntries(await Promise.all(['common.mjs','serve.mjs','worker.js','inference-config.mjs','lyrics.mjs','cache-position.mjs','decode-wire.mjs','worker-decoder-source.mjs','worker-alignment-source.mjs','audio-time-scale.mjs','recognition-map.mjs','speculative-context.mjs','vocab-subset.mjs','token-units.mjs','context-source.mjs'].map(async f=>[f,hash(await readFile(resolve(import.meta.dirname,f)))])));
  Object.assign(metadata,{language,audioPath,lyricsPath,inferenceLyricsSha256:hash(Buffer.from(lyrics)),referenceTextOnly:lyricsPath.endsWith('.srt'),annotationPolicy,cachePolicy,decoderThreads,audioTimeScale,driverHashes});
  metadata.modelPrecision=inference.precision;
  metadata.preset=process.env.SONG_PRESET??null;
  for(const file of ['attention-trim.mjs','fast-preset.mjs'])driverHashes[file]=hash(await readFile(resolve(import.meta.dirname,file)));
  return {audio,lyrics,modelPath,metadata};
}
